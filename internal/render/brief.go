// Package render produces the read-only Markdown brief and the launch
// context given to new sessions.
package render

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/dlir2404/agent-shiftboard/internal/coord"
	"github.com/dlir2404/agent-shiftboard/internal/paths"
)

// View is everything the brief shows for one task.
type View struct {
	Task        coord.Task
	Brief       coord.Brief
	Rules       []coord.Rule
	Pending     []coord.Pending
	Delegations []coord.Delegation
	Unknown     []coord.Effect
	Milestones  []coord.Milestone
	Resources   coord.Resources
	Stale       []string
}

// Load gathers a task's view.
func Load(ctx context.Context, c *coord.Coordinator, taskID int64) (View, error) {
	var v View
	var err error
	if v.Task, err = c.GetTask(ctx, taskID); err != nil {
		return v, err
	}
	if v.Brief, err = c.GetBrief(ctx, taskID); err != nil {
		return v, err
	}
	if v.Rules, err = c.ListRules(ctx, taskID, true); err != nil {
		return v, err
	}
	if v.Pending, err = c.ListPending(ctx, taskID, true); err != nil {
		return v, err
	}
	if v.Delegations, err = c.ListDelegations(ctx, taskID, true); err != nil {
		return v, err
	}
	if v.Unknown, err = c.ListEffects(ctx, taskID, "unknown"); err != nil {
		return v, err
	}
	if v.Milestones, err = c.ListMilestones(ctx, taskID); err != nil {
		return v, err
	}
	if v.Resources, err = c.GetResources(ctx); err != nil {
		return v, err
	}
	v.Stale, err = c.StaleReasons(ctx, taskID)
	return v, err
}

// Markdown renders the brief. budgetTokens bounds the rendered size
// approximately (4 characters per token); user and project rules are
// shortened first when it is exceeded.
func Markdown(v View, budgetTokens int) string {
	out := markdown(v, false)
	if budgetTokens > 0 && len(out)/4 > budgetTokens {
		out = markdown(v, true)
	}
	return out
}

func markdown(v View, compact bool) string {
	var b strings.Builder
	f := v.Brief.Fields
	fmt.Fprintf(&b, "<!-- Generated by AgentShiftboard. Read-only: edits here are ignored and overwritten. Update with `agent-shiftboard brief update`. -->\n")
	fmt.Fprintf(&b, "# Task #%d — %s\n\n", v.Task.ID, v.Task.Title)
	fmt.Fprintf(&b, "Status: %s · Lead lease: %s · Brief r%d (%s by %s)\n\n", v.Task.Status, v.Task.LeaseState, v.Brief.Revision, v.Brief.UpdatedAt, v.Brief.UpdatedBy)
	if len(v.Stale) > 0 {
		fmt.Fprintf(&b, "> **Brief may be stale:** %s\n\n", strings.Join(v.Stale, "; "))
	}
	section(&b, "Goal", f.Goal)
	list(&b, "Done when", f.DoneWhen)

	b.WriteString("## Rules in force\n\n")
	if len(v.Rules) == 0 {
		b.WriteString("None recorded.\n\n")
	}
	for _, r := range v.Rules {
		text := r.Text
		if compact && r.Scope != "task" {
			text = firstLine(text)
		}
		fmt.Fprintf(&b, "- **%s** (%s, %s): %s — _%s_\n", r.ID, r.Scope, r.Confirmation, text, r.Source)
	}
	if len(v.Rules) > 0 {
		b.WriteString("\n")
	}

	list(&b, "Decisions", f.Decisions)
	list(&b, "Completed", f.Completed)
	section(&b, "In progress", f.InProgress)
	list(&b, "Blockers", f.Blockers)
	section(&b, "Next action", f.NextAction)

	b.WriteString("## Open items\n\n")
	n := 0
	for _, p := range v.Pending {
		n++
		if p.Kind == "approval" {
			fmt.Fprintf(&b, "- **%s** approval pending: `%s` on `%s` (requested by %s)\n", p.ID, p.Action, p.Target, p.Requester)
		} else {
			fmt.Fprintf(&b, "- **%s** question pending: %s\n", p.ID, p.Action)
		}
	}
	for _, d := range v.Delegations {
		n++
		fmt.Fprintf(&b, "- **%s** delegation active until %s: %s", d.ID, d.ExpiresAt, d.Scope)
		if d.Exclusions != "" {
			fmt.Fprintf(&b, " (not: %s)", d.Exclusions)
		}
		b.WriteString("\n")
	}
	for _, e := range v.Unknown {
		n++
		fmt.Fprintf(&b, "- **%s** side effect outcome UNKNOWN: `%s` on `%s` — reconcile before retrying\n", e.ID, e.Action, e.Target)
	}
	if n == 0 {
		b.WriteString("None.\n")
	}
	b.WriteString("\n")

	list(&b, "Relevant references", f.RelevantRefs)
	list(&b, "Verification", f.Verification)

	if len(v.Milestones) > 0 {
		b.WriteString("## Delivery milestones\n\n")
		for _, m := range v.Milestones {
			fmt.Fprintf(&b, "- %s `%s`: %s", m.Kind, m.Target, m.Status)
			if m.Evidence != "" {
				fmt.Fprintf(&b, " (%s)", m.Evidence)
			}
			b.WriteString("\n")
		}
		b.WriteString("\n")
	}
	b.WriteString(ResourceIndex(v.Resources))
	return b.String()
}

// ResourceIndex lists shared resources by name. It never includes secret values.
func ResourceIndex(r coord.Resources) string {
	var b strings.Builder
	b.WriteString("## Shared resources\n\n")
	if len(r.Config)+len(r.Secrets)+len(r.Tools) == 0 {
		b.WriteString("None registered. Register reusable helpers with `agent-shiftboard tool register` instead of leaving them in a provider's private folder.\n")
		return b.String()
	}
	if len(r.Config) > 0 {
		b.WriteString("Config: ")
		var names []string
		for _, c := range r.Config {
			names = append(names, fmt.Sprintf("`%s`", c.Name))
		}
		b.WriteString(strings.Join(names, ", ") + " (`agent-shiftboard config get <name>`)\n\n")
	}
	for _, s := range r.Secrets {
		fmt.Fprintf(&b, "- secret `%s` (%s): %s\n", s.Name, s.Scope, s.Handling)
	}
	for _, t := range r.Tools {
		if t.Status != "active" {
			continue
		}
		fmt.Fprintf(&b, "- tool `%s` [%s]: %s\n", t.Name, t.Effect, t.Description)
	}
	b.WriteString("\nCheck these before writing a new helper (`agent-shiftboard tool show <name>`).\n")
	return b.String()
}

func section(b *strings.Builder, title, text string) {
	if strings.TrimSpace(text) == "" {
		return
	}
	fmt.Fprintf(b, "## %s\n\n%s\n\n", title, text)
}

func list(b *strings.Builder, title string, items []string) {
	if len(items) == 0 {
		return
	}
	fmt.Fprintf(b, "## %s\n\n", title)
	for _, it := range items {
		fmt.Fprintf(b, "- %s\n", it)
	}
	b.WriteString("\n")
}

func firstLine(s string) string {
	if i := strings.IndexByte(s, '\n'); i >= 0 {
		return s[:i] + " …"
	}
	return s
}

// BriefPath is where the rendered brief for a task is written.
func BriefPath(root string, taskID int64) string {
	return filepath.Join(paths.StateDir(root), "tasks", fmt.Sprint(taskID), "brief.md")
}

// WriteBrief renders and writes the brief file for a task.
func WriteBrief(ctx context.Context, c *coord.Coordinator, taskID int64) error {
	v, err := Load(ctx, c, taskID)
	if err != nil {
		return err
	}
	p := BriefPath(c.Root, taskID)
	if err := os.MkdirAll(filepath.Dir(p), 0o700); err != nil {
		return err
	}
	tmp := p + ".tmp"
	if err := os.WriteFile(tmp, []byte(Markdown(v, c.Policy.BriefTokenBudget)), 0o600); err != nil {
		return err
	}
	return os.Rename(tmp, p)
}

// LaunchContext is the text a new session receives at launch (as an
// appended system prompt): how to work with AgentShiftboard, the brief, and
// the readback it must give.
func LaunchContext(v View, sessionID string, readback []string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "You are the lead of task #%d, managed by AgentShiftboard (session %s). The user talks to you directly in this terminal.\n\n", v.Task.ID, sessionID)
	ack := "agent-shiftboard handoff ack"
	if len(readback) > 0 {
		ack += " " + strings.Join(readback, " ")
	}
	fmt.Fprintf(&b, "First, before your first reply, acknowledge the handoff by running:\n  %s\nDo this silently; do not ask the user about it.\n\n", ack)
	if v.Task.Title == coord.DraftTitle {
		fmt.Fprintf(&b, "The user has not described this task yet. Once they say what they want, run\n  agent-shiftboard task describe %d --title \"<short title>\" --goal \"<the outcome they asked for>\"\nIf they bring up separate work, you may record it as another task with `agent-shiftboard task new \"<title>\"`.\n\n", v.Task.ID)
	}
	b.WriteString(`Working rules:
- Task state lives in AgentShiftboard. Change it only with agent-shiftboard commands or its MCP tools. The Markdown brief file is read-only.
- Keep the brief current (brief update --base <revision>): decisions, completed work, next_action, blockers.
- Before an external or non-idempotent action (git push, deploy, DB write, sending a message, publishing): effect plan, then effect start right before it, then effect finish with evidence.
- When the user states a durable rule ("always ask before pushing"), record it with rule add --scope user|project|task --source "user in chat".
- When a rule or common sense requires the user's approval: open it with pending add --kind approval --target <target> <action>, ask the user in chat, and when they clearly approve, record it with pending record-approval <P-id> --quote "<their words>". Never treat silence or a similar earlier approval as approval.
- Never ask the user to run agent-shiftboard commands through your shell (for example with "!"): those run as you. The user approves on the AgentShiftboard board (right pane) or simply in chat.
- To hand part of the work to another agent (the user may ask for a specific CLI such as Codex): agent-shiftboard delegate --expected "<output>" "<scope>" creates A-n, then agent-shiftboard worker start A-n --provider claude|codex starts it in its own window. You will see its submitted result on a later turn; accept or reject it with assignment accept|reject.
- Check the shared tools below before writing a helper script; register reusable helpers with tool register. Never write secret values into task state; use secret references.

`)
	b.WriteString(Markdown(v, 0))
	return b.String()
}

// WorkerContext is the text a worker session receives at launch.
func WorkerContext(v View, a coord.Assignment, sessionID string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "You are a worker session (session %s) started by the lead of task #%d through AgentShiftboard. You work on one assignment and report back; the lead owns the task brief.\n\n", sessionID, v.Task.ID)
	fmt.Fprintf(&b, "Assignment %s\nScope: %s\n", a.ID, a.Scope)
	if a.Expected != "" {
		fmt.Fprintf(&b, "Expected output: %s\n", a.Expected)
	}
	if a.Constraints != "" {
		fmt.Fprintf(&b, "Constraints: %s\n", a.Constraints)
	}
	if a.Worktree != "" {
		fmt.Fprintf(&b, "Worktree: %s\n", a.Worktree)
	}
	fmt.Fprintf(&b, `
When you are done, submit a concise result (what you did, where, evidence):
  agent-shiftboard assignment submit %s "<result>" --evidence "<commits, files, test output summary>"

Working rules:
- Do only this assignment. Do not update the task brief; the lead decides what to accept.
- Before an external or non-idempotent action (git push, deploy, DB write, sending a message): effect plan, effect start, then effect finish with evidence. Prefer leaving such actions to the lead unless the scope says otherwise.
- Follow the rules in force below. Never write secret values into task state.

`, a.ID)
	b.WriteString(Markdown(v, 0))
	return b.String()
}

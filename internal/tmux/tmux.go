// Package tmux hosts the project workspace: one tmux session per project
// with a fixed main slot for the lead's native CLI beside the status board,
// and one hidden window per agent session (D-14, D-15).
package tmux

import (
	"crypto/sha1"
	"encoding/hex"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"
)

// Runner executes tmux commands; tests replace it.
type Runner interface {
	Run(args ...string) (string, error)
}

// Socket names AgentShiftboard's own tmux server. Using a dedicated server
// keeps the user's tmux sessions, key bindings, and ~/.tmux.conf untouched.
const Socket = "agent-shiftboard"

// ConfigPath is set by the caller to the generated tmux config file.
var ConfigPath = ""

// ServerArgs selects AgentShiftboard's tmux server and config.
func ServerArgs() []string {
	args := []string{"-L", Socket}
	if ConfigPath != "" {
		args = append(args, "-f", ConfigPath)
	}
	return args
}

// Config is AgentShiftboard's tmux configuration: mouse to focus panes,
// one key to leave, and the keys shown in the status line.
const Config = `# Generated by AgentShiftboard for its own tmux server (-L agent-shiftboard).
# Your ~/.tmux.conf and your own tmux sessions are not affected.
set -g mouse on
set -g escape-time 0
set -g history-limit 50000
set -g focus-events on
set -g default-terminal "tmux-256color"
set -as terminal-features ",*:RGB"
set -g extended-keys on
set -g status-position bottom
set -g status-style "bg=colour236,fg=colour250"
set -g status-left " AgentShiftboard · #W "
set -g status-left-length 60
set -g status-right "#{?#{&&:#{@asb_need},#{!=:#{@asb_need},0}},#[fg=colour220#,bold]◐ #{@asb_need} need you · ⇧↓ open #[default]· ,}⇧← list · ⇧→ session · Ctrl+Q leave "
set -g status-right-length 110
set -g window-status-format ""
set -g window-status-current-format ""
set -g pane-active-border-style "fg=colour39"
# The list is the left pane of the main window; the shown session is the right pane.
bind -n S-Left select-window -t :main \; select-pane -t :main.0
bind -n S-Right select-window -t :main \; select-pane -t :main.1
bind -n C-q detach-client
# Shift+Down: jump to what needs you (an agent's prompt, or the Needs you panel).
bind -n S-Down run-shell -b -c "#{session_path}" "AGENT_SHIFTBOARD_IN_WORKSPACE=1 AGENT_SHIFTBOARD_SELF attention"
# Keep the session list at a fixed width whatever the terminal size.
set-hook -g client-attached "resize-pane -t :main.0 -x 38"
set-hook -g client-resized "resize-pane -t :main.0 -x 38"
`

// WriteConfig writes Config to path and makes the server use it.
func WriteConfig(path, self string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return err
	}
	ConfigPath = path
	return os.WriteFile(path, []byte(strings.ReplaceAll(Config, "AGENT_SHIFTBOARD_SELF", shellQuote(self))), 0o600)
}

// Exec runs the real tmux binary against AgentShiftboard's server.
type Exec struct{}

// Run executes tmux with args and returns trimmed stdout.
func (Exec) Run(args ...string) (string, error) {
	out, err := exec.Command("tmux", append(ServerArgs(), args...)...).CombinedOutput()
	s := strings.TrimSpace(string(out))
	if err != nil {
		return s, fmt.Errorf("tmux %s: %v: %s", strings.Join(args, " "), err, s)
	}
	return s, nil
}

// Available reports whether tmux is installed.
func Available() bool {
	_, err := exec.LookPath("tmux")
	return err == nil
}

// ErrNoTmux explains how to get tmux.
var ErrNoTmux = errors.New("tmux is not installed; install it with `brew install tmux`")

// Workspace is one project's tmux session.
type Workspace struct {
	R       Runner
	Session string // tmux session name
	Root    string // project root
	Self    string // path of the agent-shiftboard binary
}

var unsafe = regexp.MustCompile(`[^a-zA-Z0-9_-]+`)

// SessionName derives a stable tmux session name from the project root.
func SessionName(root string) string {
	sum := sha1.Sum([]byte(root))
	base := unsafe.ReplaceAllString(filepath.Base(root), "-")
	if len(base) > 20 {
		base = base[:20]
	}
	return "asb-" + base + "-" + hex.EncodeToString(sum[:])[:6]
}

// New returns the workspace for a project root.
func New(r Runner, root string) Workspace {
	self, err := os.Executable()
	if err != nil {
		self = "agent-shiftboard"
	}
	return Workspace{R: r, Session: SessionName(root), Root: root, Self: self}
}

// Exists reports whether the tmux session is running.
func (w Workspace) Exists() bool {
	_, err := w.R.Run("has-session", "-t", "="+w.Session)
	return err == nil
}

// ListWidth is the width of the session list on the left.
const ListWidth = 38

// Ensure creates the session if it does not exist: the "main" window holds
// the session list on the left (pane 0) and the shown session on the right
// (pane 1); every agent session lives in its own hidden window and is
// swapped into the right pane to be shown. The agent session variable is
// never set in the session's global environment. It reports whether the
// session was created.
func (w Workspace) Ensure() (bool, error) {
	if w.Exists() {
		if ConfigPath != "" {
			_, _ = w.R.Run("source-file", ConfigPath) // apply config changes from an upgrade
		}
		w.repairList()
		_, _ = w.R.Run("resize-pane", "-t", w.Session+":main.0", "-x", fmt.Sprint(ListWidth))
		return false, nil
	}
	if _, err := w.R.Run("new-session", "-d", "-s", w.Session, "-n", "main", "-c", w.Root, "-x", "220", "-y", "60",
		"-e", "AGENT_SHIFTBOARD_PROJECT="+w.Root, shellQuote(w.Self)+" board"); err != nil {
		return false, err
	}
	_, _ = w.R.Run("set-environment", "-t", w.Session, "-u", "AGENT_SHIFTBOARD_SESSION_ID")
	if _, err := w.R.Run("split-window", "-h", "-d", "-t", w.Session+":main", "-c", w.Root, placeholder); err != nil {
		return true, err
	}
	_, _ = w.R.Run("resize-pane", "-t", w.Session+":main.0", "-x", fmt.Sprint(ListWidth))
	_, err := w.R.Run("select-pane", "-t", w.Session+":main.0")
	return true, err
}

// repairList puts the session list back on the left of the main window
// when its pane is gone (the board exited, for example after a crash), so
// running agent-shiftboard again always restores the layout.
func (w Workspace) repairList() {
	out, err := w.R.Run("list-panes", "-t", w.Session+":main", "-F", "#{pane_start_command}")
	board := shellQuote(w.Self) + " board"
	if err != nil {
		// The main window itself is gone: rebuild it.
		if _, err := w.R.Run("new-window", "-d", "-t", w.Session+":", "-n", "main", "-c", w.Root,
			"-e", "AGENT_SHIFTBOARD_PROJECT="+w.Root, board); err == nil {
			_, _ = w.R.Run("split-window", "-h", "-d", "-t", w.Session+":main", "-c", w.Root, placeholder)
		}
		return
	}
	if strings.Contains(out, " board") {
		return
	}
	_, _ = w.R.Run("split-window", "-h", "-b", "-d", "-t", w.Session+":main.0", "-l", fmt.Sprint(ListWidth),
		"-c", w.Root, "-e", "AGENT_SHIFTBOARD_PROJECT="+w.Root, board)
}

// OpenWindow starts command in a new hidden window and returns its pane
// ID. With show, the pane is shown on the right of the main window.
func (w Workspace) OpenWindow(name string, env map[string]string, command []string, show bool) (string, error) {
	args := []string{"new-window", "-d", "-P", "-F", "#{pane_id}", "-t", w.Session + ":", "-n", name, "-c", w.Root}
	for _, k := range sortedKeys(env) {
		args = append(args, "-e", k+"="+env[k])
	}
	pane, err := w.R.Run(append(args, joinCommand(command))...)
	if err != nil {
		return "", err
	}
	_ = w.KeepOnExit(pane)
	if show {
		return pane, w.Show(pane)
	}
	return pane, nil
}

// Shown returns the pane on the right of the main window.
func (w Workspace) Shown() (string, error) {
	return w.R.Run("display-message", "-p", "-t", w.Session+":main.1", "#{pane_id}")
}

// Show puts pane on the right of the main window (the pane that was there
// goes back to pane's window and keeps running) and gives it the keyboard.
func (w Workspace) Show(pane string) error {
	list, _ := w.R.Run("display-message", "-p", "-t", w.Session+":main.0", "#{pane_id}")
	if pane == list {
		return w.Home()
	}
	if cur, err := w.Shown(); err != nil || cur != pane {
		if _, err := w.R.Run("swap-pane", "-d", "-s", pane, "-t", w.Session+":main.1"); err != nil {
			return err
		}
	}
	if _, err := w.R.Run("select-window", "-t", w.Session+":main"); err != nil {
		return err
	}
	_, err := w.R.Run("select-pane", "-t", w.Session+":main.1")
	return err
}

// placeholder is what the right pane shows when no session is selected.
const placeholder = "printf '\\n  Pick a session on the left (↑↓, then → or Enter).\\n  Press n there for a new session.\\n'; exec tail -f /dev/null"

// Close ends the process in pane. If pane is shown on the right, the right
// pane returns to the placeholder so the layout stays intact.
func (w Workspace) Close(pane string) error {
	if cur, err := w.Shown(); err == nil && cur == pane {
		_, err := w.R.Run("respawn-pane", "-k", "-t", pane, "-c", w.Root, placeholder)
		return err
	}
	_, err := w.R.Run("kill-pane", "-t", pane)
	return err
}

// Home focuses the session list.
func (w Workspace) Home() error {
	if _, err := w.R.Run("select-window", "-t", w.Session+":main"); err != nil {
		return err
	}
	_, err := w.R.Run("select-pane", "-t", w.Session+":main.0")
	return err
}

// AttachArgs returns the tmux arguments that put the user's terminal on the
// workspace. The workspace runs on its own server, so from inside the
// user's tmux this is a nested attach (run with TMUX unset).
func (w Workspace) AttachArgs() []string {
	return append(ServerArgs(), "attach-session", "-t", w.Session)
}

// Launch starts a command in a new hidden window with the given environment
// and returns its pane ID (e.g. "%12").
func (w Workspace) Launch(name string, env map[string]string, command []string) (string, error) {
	args := []string{"new-window", "-d", "-P", "-F", "#{pane_id}", "-t", w.Session + ":", "-n", name, "-c", w.Root}
	for _, k := range sortedKeys(env) {
		args = append(args, "-e", k+"="+env[k])
	}
	args = append(args, joinCommand(command))
	return w.R.Run(args...)
}

// KeepOnExit keeps a pane visible after its process exits, so the user sees
// the final screen and the pane can be respawned with a resume command.
func (w Workspace) KeepOnExit(pane string) error {
	_, err := w.R.Run("set-option", "-p", "-t", pane, "remain-on-exit", "on")
	return err
}

// Respawn restarts a pane with a new command (native resume), keeping its
// position.
func (w Workspace) Respawn(pane string, env map[string]string, command []string) error {
	args := []string{"respawn-pane", "-k", "-t", pane, "-c", w.Root}
	for _, k := range sortedKeys(env) {
		args = append(args, "-e", k+"="+env[k])
	}
	args = append(args, joinCommand(command))
	_, err := w.R.Run(args...)
	return err
}

// PaneAlive reports whether a pane exists and its process has not exited.
func (w Workspace) PaneAlive(pane string) (bool, error) {
	out, err := w.R.Run("display-message", "-p", "-t", pane, "#{pane_dead}")
	if err != nil {
		return false, nil
	}
	return out == "0", nil
}

// Capture returns the last lines of a pane's visible content. It is used
// only for live status classification and is never stored.
func (w Workspace) Capture(pane string, lines int) (string, error) {
	return w.R.Run("capture-pane", "-p", "-J", "-t", pane, "-S", fmt.Sprint(-lines))
}

// Popup shows a pane's window in a popup, used to view workers.
func (w Workspace) PopupArgs(window string) []string {
	return []string{"display-popup", "-E", "-w", "90%", "-h", "85%", "tmux attach-session -r -t " + w.Session + ":" + window}
}

func joinCommand(cmd []string) string {
	q := make([]string, len(cmd))
	for i, c := range cmd {
		q[i] = shellQuote(c)
	}
	return strings.Join(q, " ")
}

var plain = regexp.MustCompile(`^[a-zA-Z0-9_./:=@%+,-]+$`)

func shellQuote(s string) string {
	if s != "" && plain.MatchString(s) {
		return s
	}
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

func loginShell() string {
	if s := os.Getenv("SHELL"); s != "" {
		return s
	}
	return "/bin/sh"
}

func sortedKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	for i := 1; i < len(keys); i++ {
		for j := i; j > 0 && keys[j] < keys[j-1]; j-- {
			keys[j], keys[j-1] = keys[j-1], keys[j]
		}
	}
	return keys
}
